# 4. Fungsi Augmentasi (Menambah Noise pada Failure)
def augment_failure_data(X, y_clf, y_reg, augment_factor=15):
    X_aug, y_clf_aug, y_reg_aug = [], [], []

    failure_indices = np.where(y_clf == 1)[0]
    normal_indices = np.where(y_clf == 0)[0]

    # Tambah data Normal (asli)
    X_aug.append(X[normal_indices])
    y_clf_aug.append(y_clf[normal_indices])
    y_reg_aug.append(y_reg[normal_indices])

    # Tambah data Failure (asli + augmented)
    X_aug.append(X[failure_indices])
    y_clf_aug.append(y_clf[failure_indices])
    y_reg_aug.append(y_reg[failure_indices])

    for idx in failure_indices:
        for _ in range(augment_factor - 1):
            seq = X[idx].copy()
            noise = np.random.normal(0, 0.02, seq.shape)
            seq_aug = np.clip(seq + noise, 0, 1)

            X_aug.append(seq_aug.reshape(1, seq.shape[0], seq.shape[1]))
            y_clf_aug.append(np.array([y_clf[idx]]))
            y_reg_aug.append(np.array([y_reg[idx]]))

    return np.concatenate(X_aug, axis=0), np.concatenate(y_clf_aug, axis=0), np.concatenate(y_reg_aug, axis=0)

