# ==========================================
# CELL 16 : CLASSIFICATION + FOCAL LOSS + THRESHOLD OPTIMIZATION
# ==========================================
import tensorflow as tf
import numpy as np
import matplotlib.pyplot as plt
from sklearn.metrics import precision_recall_curve, average_precision_score, f1_score

print("Memperbaiki Model Klasifikasi dengan Focal Loss...")

# Definisikan Focal Loss (lebih sensitif ke minority class)
def focal_loss(gamma=2.0, alpha=0.25):
    def focal_loss_fixed(y_true, y_pred):
        y_true = tf.cast(y_true, tf.float32)
        bce = tf.keras.losses.binary_crossentropy(y_true, y_pred)
        p_t = y_true * y_pred + (1 - y_true) * (1 - y_pred)
        loss = alpha * tf.pow(1 - p_t, gamma) * bce
        return tf.reduce_mean(loss)
    return focal_loss_fixed

# Bangun ulang GRU dengan Focal Loss
model_gru_fixed = tf.keras.Sequential([
    tf.keras.layers.Input(shape=(X_train_aug.shape[1], X_train_aug.shape[2])),
    tf.keras.layers.GRU(64, return_sequences=False, kernel_regularizer=tf.keras.regularizers.l2(0.001)),
    tf.keras.layers.Dropout(0.4),
    tf.keras.layers.Dense(32, activation='relu'),
    tf.keras.layers.Dropout(0.3),
    tf.keras.layers.Dense(1, activation='sigmoid')
])

model_gru_fixed.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=5e-5, clipvalue=1.0),
    loss=focal_loss(gamma=2.0, alpha=0.75),  # alpha tinggi ke class 1 (failure)
    metrics=['accuracy']
)

print("Model GRU Fixed siap dengan Focal Loss!")

# Training ulang (hanya 15 epoch, early stopping ketat)
