"""#C16 Opsi2FocalLossThreshold"""

# ==========================================
# CELL 16: SARAN C2 - FOCAL LOSS + THRESHOLD
# ==========================================
print("🎯 Cell 16: Focal Loss & Threshold Tuning...")
def focal_loss(g=2.0, a=0.25):
    def loss(yt, yp):
        yt = tf.cast(yt, tf.float32)
        bce = tf.keras.losses.binary_crossentropy(yt, yp)
        pt = yt*yp + (1-yt)*(1-yp)
        return tf.reduce_mean(a * tf.pow(1-pt, g) * bce)
    return loss

