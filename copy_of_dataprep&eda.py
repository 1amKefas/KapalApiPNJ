feat_cols = [c for c in ['temperature','vibration','pressure','rpm','temperature_roll_mean','temperature_roll_std','days_since_maint'] if c in df_merged.columns]

def make_seq(df, seq=24):
    X, yc, yr = [], [], []
    for m in df['machine_id'].unique():
        md = df[df['machine_id']==m].sort_values('timestamp')
        if len(md)<=seq: continue
        X.append(md[feat_cols].values.astype(np.float32))
        yc.append(md['failure_7d'].values.astype(np.int8))
        yr.append(md['RUL_days'].values.astype(np.float32))

    X_s, yc_s, yr_s = [], [], []
    for x, c, r in zip(X, yc, yr):
        for i in range(len(x)-seq):
            X_s.append(x[i:i+seq])
            yc_s.append(c[i+seq])
            yr_s.append(r[i+seq])
    return np.array(X_s, dtype=np.float32), np.array(yc_s, dtype=np.int8), np.array(yr_s, dtype=np.float32)

