# 1. Pastikan data terurut berdasarkan waktu (WAJIB untuk merge_asof)
# Urutan sorting harus mendahulukan kunci waktu agar terbaca sebagai sorted oleh pandas
df_sensor = df_sensor.sort_values('timestamp')
df_maint = df_maint.sort_values('date')

# 2. Merge Asof: Gabungin data sensor dengan maintenance TERDEKAT sebelumnya
# Ini supaya setiap baris sensor tau kapan terakhir kali dia diservis
df_merged = pd.merge_asof(
    df_sensor,
    df_maint[['date', 'machine_id', 'maintenance_type', 'downtime_hours']],
    left_on='timestamp',
    right_on='date',
    by='machine_id',
    direction='backward'
)

# 3. Hitung 'Days Since Last Maintenance' (DSLM)
# Fitur ini krusial: Makin lama nggak dirawat, risiko failure biasanya naik.
df_merged['days_since_last_maint'] = (df_merged['timestamp'] - df_merged['date']).dt.total_seconds() / (24 * 3600)

# Jika mesin belum pernah diservis (NaN), kita isi dengan operating_hours-nya
df_merged['days_since_last_maint'] = df_merged['days_since_last_maint'].fillna(df_merged['operating_hours'] / 24)

print("✅ Merging sukses! Fitur 'Days Since Last Maintenance' siap digunakan.")
display(df_merged[['machine_id', 'timestamp', 'days_since_last_maint']].head())

"""# 11.RollingStatistics&LagFeatures"""

# ==========================================
# CELL 11: ROLLING STATISTICS & LAG FEATURES
# ==========================================

sensor_cols = ['temperature', 'vibration', 'pressure', 'rpm', 'power_consumption']
window_size = 24 # Kita liat rata-rata dalam jendela 24 jam

# 1. Rolling Mean & Std: Menangkap anomali yang perlahan naik/turun
for col in sensor_cols:
    df_merged[f'{col}_rolling_mean'] = df_merged.groupby('machine_id')[col].transform(lambda x: x.rolling(window=window_size).mean())
    df_merged[f'{col}_rolling_std'] = df_merged.groupby('machine_id')[col].transform(lambda x: x.rolling(window=window_size).std())

# 2. Lag Features: Memberi tahu model kondisi di t-1 (satu jam sebelumnya)
for col in sensor_cols:
    df_merged[f'{col}_lag1'] = df_merged.groupby('machine_id')[col].shift(1)

# Hapus baris awal yang NaN karena proses rolling/lag
df_final = df_merged.dropna().reset_index(drop=True)

print(f"✅ Feature Engineering selesai! Total fitur sekarang: {df_final.shape[1]}")

"""# 12.TrainTestSplit"""

