def aug_seq(X, y, factor=12):
    f_idx = np.where(y==1)[0]
    n_idx = np.where(y==0)[0]
    X_a, y_a = [X[n_idx]], [y[n_idx]]
    X_a.append(X[f_idx]); y_a.append(y[f_idx])
    for i in f_idx:
        for _ in range(factor-1):
            seq = X[i].copy() + np.random.normal(0, 0.02, X[i].shape)
            X_a.append(np.clip(seq, 0, 1).reshape(1, seq.shape[0], seq.shape[1]))
            y_a.append(np.array([y[i]]))
    return np.concatenate(X_a, axis=0), np.concatenate(y_a, axis=0)

