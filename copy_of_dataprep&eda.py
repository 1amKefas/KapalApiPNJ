def create_sequences(df, seq_len=24):
    X, y_clf, y_reg = [], [], []
    for m_id in df['machine_id'].unique():
        m_data = df[df['machine_id']==m_id].sort_values('timestamp')[feature_cols].values.astype(np.float32)
        clf_labels = df[df['machine_id']==m_id].sort_values('timestamp')['failure_7d'].values.astype(np.int8)
        reg_labels = df[df['machine_id']==m_id].sort_values('timestamp')['RUL_days'].values.astype(np.float32)

        if len(m_data) <= seq_len: continue

        for i in range(len(m_data) - seq_len):
            X.append(m_data[i:i+seq_len])
            y_clf.append(clf_labels[i+seq_len])
            y_reg.append(reg_labels[i+seq_len])

    return np.array(X, dtype=np.float32), np.array(y_clf, dtype=np.int8), np.array(y_reg, dtype=np.float32)

